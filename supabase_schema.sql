-- Rulează întregul fișier în Supabase → SQL Editor. Este idempotent: poate fi rulat din nou
-- fără să șteargă date (completează tabelele din v6 cu coloanele noi).
-- Securitate: Row Level Security este activ; fiecare utilizatoare autentificată poate citi și
-- adăuga DOAR propriile rânduri (auth.uid() = user_id). Rolul anon nu are acces la tabele.
-- Istoricul nu se modifică și nu se șterge din aplicație (nu există politici UPDATE/DELETE).
