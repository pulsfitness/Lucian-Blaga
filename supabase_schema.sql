-- 1. Încercări (istoricul complet al răspunsurilor)
create table if not exists public.answers (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  question_id text not null,
  domain text not null,
  topic text not null,
  chosen text not null,
  correct_answer text not null,
  is_correct boolean not null,
  created_at timestamptz default now()
);

alter table public.answers add column if not exists lesson text;
alter table public.answers add column if not exists question_text text;
alter table public.answers add column if not exists source text not null default 'test';
alter table public.answers add column if not exists client_ref text;
alter table public.answers alter column user_id set default auth.uid();
do $$ begin
  -- created_at devine obligatoriu doar dacă nu există rânduri vechi fără dată (nu modificăm datele existente)
  if not exists (select 1 from public.answers where created_at is null) then
    alter table public.answers alter column created_at set not null;
  end if;
end $$;

do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'answers_source_check') then
    alter table public.answers add constraint answers_source_check
      check (source in ('test', 'daily', 'mistake_retry'));
  end if;
  if not exists (select 1 from pg_constraint where conname = 'answers_user_client_ref_key') then
    -- împiedică dublurile la importul opțional al progresului local (NULL-urile nu intră în conflict)
    alter table public.answers add constraint answers_user_client_ref_key unique (user_id, client_ref);
  end if;
end $$;

create index if not exists answers_user_id_idx on public.answers (user_id, id);
create index if not exists answers_user_question_idx on public.answers (user_id, question_id, id);

-- 2. Provocarea zilei: cel mult un rezultat pe utilizatoare și zi
create table if not exists public.daily_challenges (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  challenge_date date not null,
  question_id text not null,
  chosen text not null,
  is_correct boolean not null,
  created_at timestamptz not null default now(),
  primary key (user_id, challenge_date)
);

-- 3. Drepturi: doar utilizatorii autentificați; anon nu vede nimic
revoke all on public.answers from anon;
revoke all on public.daily_challenges from anon;
grant select, insert on public.answers to authenticated;
grant select, insert on public.daily_challenges to authenticated;
grant all on public.answers to service_role;
grant all on public.daily_challenges to service_role;

-- 4. Row Level Security
alter table public.answers enable row level security;
alter table public.daily_challenges enable row level security;

drop policy if exists "read own answers" on public.answers;
drop policy if exists "insert own answers" on public.answers;
create policy "read own answers" on public.answers
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "insert own answers" on public.answers
  for insert to authenticated with check ((select auth.uid()) = user_id);

drop policy if exists "read own daily" on public.daily_challenges;
drop policy if exists "insert own daily" on public.daily_challenges;
create policy "read own daily" on public.daily_challenges
  for select to authenticated using ((select auth.uid()) = user_id);
create policy "insert own daily" on public.daily_challenges
  for insert to authenticated with check ((select auth.uid()) = user_id);

-- 5. Înregistrarea atomică a provocării zilei (security invoker → RLS se aplică normal).
--    Întoarce true dacă rezultatul a fost salvat acum, false dacă ziua era deja înregistrată
--    (reîncărcarea paginii, dublu clic sau alt dispozitiv nu creează rezultate multiple).
create or replace function public.submit_daily_challenge(
  p_challenge_date date, p_question_id text, p_domain text, p_topic text, p_lesson text,
  p_question_text text, p_chosen text, p_correct_answer text, p_is_correct boolean)
returns boolean
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_uid uuid := auth.uid();
  v_inserted int;
begin
  if v_uid is null then
    raise exception 'Utilizator neautentificat' using errcode = '28000';
  end if;
  insert into public.daily_challenges (user_id, challenge_date, question_id, chosen, is_correct)
  values (v_uid, p_challenge_date, p_question_id, p_chosen, p_is_correct)
  on conflict (user_id, challenge_date) do nothing;
  get diagnostics v_inserted = row_count;
  if v_inserted = 0 then
    return false;
  end if;
  insert into public.answers (user_id, question_id, domain, topic, lesson, question_text, chosen,
                              correct_answer, is_correct, source)
  values (v_uid, p_question_id, p_domain, p_topic, p_lesson, p_question_text, p_chosen,
          p_correct_answer, p_is_correct, 'daily');
  return true;
end $$;

revoke all on function public.submit_daily_challenge(date, text, text, text, text, text, text, text, boolean) from public, anon;
grant execute on function public.submit_daily_challenge(date, text, text, text, text, text, text, text, boolean) to authenticated;
